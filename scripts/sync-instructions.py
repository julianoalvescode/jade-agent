#!/usr/bin/env python3
"""Generate portable instructions from the canonical workflow skill."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def outputs(root=ROOT):
    body = (root / 'skills/jade-workflow/SKILL.md').read_text(encoding='utf-8').split('---', 2)[2].lstrip()
    notice = '<!-- Generated by scripts/sync-instructions.py; edit skills/jade-workflow/SKILL.md. -->\n\n'
    return {
        'AGENTS.md': notice + body,
        'AGENT-PROMPT.md': notice + body,
        '.claude/agents/jade.md': (
            '---\nname: jade\ndescription: Senior full-stack engineer: implement and review front end '
            'and back end with a focus on quality, scalability, security, performance and UI/UX, using '
            'Jira, Confluence, GitHub, Figma and OpenSpec context; deliver evidence per criterion.\n'
            'model: inherit\npermissionMode: default\nskills:\n  - jade-workflow\n  - jade-openspec\n---\n\n'
            + notice + 'Apply `jade-workflow` as the core and always run with `jade-openspec`. Load the '
            'specific skills according to the task impact, preserving the project rules and authorizations.\n'
        ),
    }

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        parser.exit(1, 'Out-of-date instructions: ' + ', '.join(stale) + '\n')
    print('Instructions synchronized.')

if __name__ == '__main__':
    main()
